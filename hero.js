/* Landing figure: two-path interference. Each output receives one arrow from the path through 0
   (blue, amplitude 1/2) and one from the path through 1 (violet, amplitude e^{iφ}/2, or its negative
   for output 1); the probability is the squared length of their sum. The drawing is generated by
   scripts/build.py (interference_hero); this script only moves the parts that depend on φ. */
(() => {
  const figure = document.querySelector('.interference-hero');
  if (!figure) return;
  const $ = id => document.getElementById(id);
  const slider = $('hx-phase'), value = $('hx-value'), hand = $('hx-hand'), desc = $('hx-desc');
  const reduced = matchMedia('(prefers-reduced-motion: reduce)');
  const set = (el, attrs) => { for (const k in attrs) el.setAttribute(k, attrs[k].toFixed ? attrs[k].toFixed(2) : attrs[k]); };
  const R = 13, DIAL = 304, ROWS = [96, 204];
  let phi = Number(slider.value) / 100;   // in units of π

  function draw(describe) {
    const a = Math.PI * phi;
    set(hand, {x2: Number(hand.getAttribute('x1')) + 8 * Math.cos(a), y2: Number(hand.getAttribute('y1')) - 8 * Math.sin(a)});
    ROWS.forEach((cy, k) => {
      const theta = a + Math.PI * k, bx = DIAL + 19;
      const vx = bx + 19 * Math.cos(theta), vy = cy - 19 * Math.sin(theta);
      const prob = ((vx - DIAL) ** 2 + (vy - cy) ** 2) / 1444;   // unit circle: amplitude 1
      set($('hx-v' + k), {x2: vx, y2: vy});
      set($('hx-r' + k), {x2: vx, y2: vy});
      set($('hx-t' + k), {cx: vx, cy: vy});
      set($('hx-o' + k), {r: R * Math.sqrt(prob)});
      $('hx-p' + k).textContent = `P = ${prob.toFixed(2)}`;
    });
    value.textContent = `${phi.toFixed(2)}π`;
    if (describe) desc.textContent = desc.textContent.replace(/At phase .*$/, `At phase ${phi.toFixed(2)} pi the probability of 0 is ${(Math.cos(a / 2) ** 2).toFixed(2)}.`);
  }

  // Until the reader takes the slider, the phase sweeps slowly through a full turn and back.
  // The shared Pause motion button (theme.js) and reduced-motion settings stop the sweep.
  let auto = true, start = null;
  const stopAuto = () => { auto = false; };
  ['pointerdown', 'keydown'].forEach(type => slider.addEventListener(type, stopAuto));
  slider.addEventListener('input', () => { auto = false; phi = Number(slider.value) / 100; draw(true); });
  function tick(now) {
    const still = reduced.matches || figure.classList.contains('motion-paused') || figure.classList.contains('offscreen');
    if (auto && !still) {
      if (start === null) start = now - Math.acos(1 - phi) / (2 * Math.PI) * 18000;
      phi = 1 - Math.cos(2 * Math.PI * (now - start) / 18000);   // 0 → 2 → 0 over 18 s
      slider.value = Math.round(phi * 100);
      draw(false);
    } else start = null;
    if (auto) requestAnimationFrame(tick);
  }
  draw(false);
  requestAnimationFrame(tick);
})();
